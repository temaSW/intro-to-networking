def sdh_placement():
    b=text(28,32,'Один VC-4 может пересекать границу двух кадров STM-1','mf-heading')
    b+=text(28,67,'Пример: начало VC-4 -- в строке 3; семь его строк здесь, ещё две -- в следующем кадре.','mf-small')
    for f,x in enumerate([72,594]):
        y,rh,cw=132,27,1.5
        b+=text(x+202,106,'STM-1 № n' if f==0 else 'STM-1 № n + 1','mf-bold','middle')
        for r in range(9):
            b+=rect(x,y+r*rh,9*cw,rh,'mt-pointer' if r==3 else 'mt-section',0)
            selected=(r>=2 if f==0 else r<2)
            b+=rect(x+9*cw,y+r*rh,261*cw,rh,'mt-container' if selected else 'mf-enclosure',0)
            b+=text(x-9,y+r*rh+19,str(r+1),'mf-small','end')
        # The selected VC-4 has its J1 byte at the first payload position of row 3.
        if f==0:
            b+=rect(x+9*cw,y+2*rh,cw,rh,'mt-pointer',0)
            b+=path(f'M{x+5} {y+3.5*rh} H{x+40} V{y+2.5*rh} H{x+9*cw}','mt-pointer-link',True)
            b+=text(x+65,y+2*rh+19,'Начало VC-4','mf-small')
        else:
            b+=text(x+65,y+rh+19,'Конец VC-4','mf-small')
        b+=text(x+215,409,'7 строк выбранного VC-4' if f==0 else '2 строки того же VC-4','mf-bold','middle')
    b+=text(28,466,'Цветом выделен один и тот же VC-4. Серые области -- соседние контейнеры во времени.','mf-small')
    b+=text(28,501,'Указатель находится в строке 4, но начало контейнера в этом примере -- в строке 3.','mf-small')
    b+=text(28,536,'Чтение байтов идёт по строкам слева направо; заголовки STM-1 не входят в VC-4.','mf-small')
    figure('sdh-placement','Размещение VC-4 через границу кадров STM-1',
           'Два последовательных кадра STM-1. Выбранный VC-4 начинается в первой позиции области контейнера строки 3 первого кадра, занимает его строки 3–9 и строки 1–2 следующего кадра. Указатель в фиксированной строке 4 показывает начало VC-4; серые области принадлежат предыдущему и следующему VC-4.',b,565,
           'Показан допустимый частный случай без корректировки указателя между кадрами; начало выбрано на границе строки для наглядности. В общем случае оно может находиться внутри строки. Цвет относится к одному VC-4, а не ко всей области полезной нагрузки. Это размещение VC-4; E1 переносится в контейнере другого уровня.')


