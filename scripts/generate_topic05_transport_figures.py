def pcm_multiframe():
    b=text(28,32,'Сверхцикл: 16 циклов × 125 мкс = 2 мс','mf-heading')
    b+=text(28,64,'Разворачиваем КИ16: по четыре сигнальных бита на каждый из 30 речевых каналов.','mf-small')
    # Grouped voice columns keep the actual time-slot order; TS16 has two four-bit halves.
    edges=[28,98,213,410,588,766,1012]
    titles=['Цикл','КИ0','КИ1–15','КИ16: биты 1–4','КИ16: биты 5–8','КИ17–31']
    for i,label in enumerate(titles): b+=text((edges[i]+edges[i+1])/2,102,label,'mt-table-head','middle')
    for n in range(16):
        y=116+n*27
        for i in range(6):
            cls='mt-pointer' if i in [3,4] else 'mt-section' if i==1 else 'mf-enclosure'
            b+=rect(edges[i],y,edges[i+1]-edges[i],27,cls,0)
        values=[str(n),'ЦС' if n%2==0 else 'служ.','отсчёты каналов 1–15', '0000' if n==0 else f'abcd канала {n}', 'xyxx' if n==0 else f'abcd канала {n+15}','отсчёты каналов 16–30']
        for i,label in enumerate(values): b+=text((edges[i]+edges[i+1])/2,y+19,label,'mt-table-cell','middle')
    b+=text(28,584,'ЦС: в КИ0 через цикл передаётся комбинация 0011011 для поиска границы цикла.','mf-small')
    b+=text(28,614,'0000 в КИ16 цикла 0 задаёт начало сверхцикла сигнализации; xyxx -- служебные биты.','mf-small')
    b+=text(28,652,'За 2 мс: 16 отсчётов каждого речевого канала и один набор abcd его сигнализации.','mf-bold')
    figure('pcm-multiframe','Сверхцикл поканальной сигнализации ИКМ-30/32',
           'Строки -- циклы 0–15. Каждая строка содержит КИ0, речевые КИ1–15, КИ16 и речевые КИ17–31. КИ16 цикла 0 содержит 0000xyxx, цикла 1 -- abcd каналов 1 и 16, цикла 2 -- каналов 2 и 17, вплоть до каналов 15 и 30 в цикле 15.',b,680,
           'Речевые столбцы сгруппированы, а КИ16 увеличен для чтения двух четырёхбитовых групп; ширина столбцов не является масштабом времени. a, b, c, d -- сигнальные биты, не отсчёты речи. Показан сверхцикл поканальной сигнализации; организация CRC-4 в КИ0 -- отдельная структура.')


