export const TCP_STORY_LENGTHS = [4, 5, 5, 5];

export function tcpStory(scene = 0, step = 0) {
  const mode = Math.max(0, Math.min(3, Math.trunc(Number(scene) || 0)));
  const index = Math.max(0, Math.min(TCP_STORY_LENGTHS[mode] - 1, Math.trunc(Number(step) || 0)));
  const titles = ['Одно нормальное соединение', 'Одна попытка без завершения', 'Множество незавершённых попыток', 'Те же попытки с защитой состояния'];
  const explanations = [
    ['Клиент ещё не обращался. В таблице ожидания нет записи об этой попытке.',
      'Сервер получил SYN и создал одну запись: нужно помнить о начатом соединении.',
      'Сервер отправил SYN + ACK. Запись остаётся: сервер ждёт завершающее подтверждение.',
      'Сервер получил завершающий ACK. Соединение установлено; запись больше не занимает таблицу ожидания.'],
    ['Начальные условия те же. Эта попытка не будет завершена клиентом.',
      'Сервер получил SYN и создал запись, как при обычном соединении.',
      'Сервер отправил SYN + ACK и ждёт. По первым двум сообщениям он ещё не знает, придёт ли ACK.',
      'ACK не пришёл. Запись всё ещё занята; это пока одна из шести записей.',
      'Через 10 с после создания срок ожидания истёк. Незавершённая запись удалена, место снова свободно.'],
    ['Рассмотрим маленькую таблицу на шесть записей. Новые попытки поступят до истечения тайм-аутов.',
      'Два клиента начали соединения, но не завершают обмен. Заняты две записи.',
      'Ещё две незавершённые попытки. Заняты четыре записи; первые ещё не успели истечь.',
      'Шесть незавершённых попыток заняли всю таблицу. Свободных записей нет.',
      'Теперь обращается обычный клиент. Для его попытки нет свободной записи -- она не принята. Канал при этом может быть свободен.'],
    ['Таблица та же. Теперь сервер не хранит запись ожидания до корректного завершающего ACK.',
      'Пришли те же шесть незавершённых попыток. Сервер ответил SYN + ACK с проверочной информацией в номере последовательности. Записей ожидания нет.',
      'Новый обычный клиент отправил SYN. Сервер ещё не выделяет ему запись ожидания.',
      'Сервер ответил обычному клиенту SYN + ACK с проверочной информацией в номере последовательности. Запись ожидания не создаётся.',
      'Обычный клиент штатно подтвердил ответ. Сервер проверил ACK и создал состояние установленного соединения. Таблица ожидания по-прежнему свободна.'],
  ];
  const used = mode === 3 ? 0 : mode === 2 ? Math.min(index * 2, 6) : index > 0 && !(mode === 0 && index === 3) && !(mode === 1 && index === 4) ? 1 : 0;
  return { scene: mode, step: index, length: TCP_STORY_LENGTHS[mode], title: titles[mode],
    explanation: explanations[mode][index], used, capacity: 6,
    syn: (mode < 2 && index >= 1) || (mode === 3 && index >= 2),
    synAck: (mode < 2 && index >= 2) || (mode === 3 && index >= 3),
    ack: (mode === 0 && index >= 3) || (mode === 3 && index >= 4), missing: mode === 1 && index >= 3,
    expired: mode === 1 && index === 4, established: (mode === 0 && index === 3) || (mode === 3 && index === 4),
    burst: mode >= 2 && index >= 1, rejected: mode === 2 && index === 4,
    protected: mode === 3, checked: mode === 3 && index === 4,
    probe: mode === 3 ? (index < 2 ? 'Ещё не обращался' : index === 2 ? 'Отправил SYN' : index === 3 ? 'Получил SYN + ACK' : 'Соединение установлено после проверки ACK')
      : mode !== 2 ? null : index < 4 ? 'Ещё не обращался' : 'Не принят: свободных записей нет' };
}
